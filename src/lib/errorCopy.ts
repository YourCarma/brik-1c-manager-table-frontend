export function errorCopy(kind: ErrorKind, serverMessage = ''): ErrorCopy {
  if (kind === 'period') {
    return {
      title: 'Период не распознан',
      body: ['Расчёт не запускался, цифры не затронуты.', hintFromServer(serverMessage)],
      actions: ['fix-period'],
    }
  }

  if (kind === 'aborted') {
    return {
      title: 'Расчёт прерван',
      body: [
        'Расчёт остановлен по вашему указанию. Файл не сформирован, результата нет.',
        'В 1С ничего не изменилось: сервис работает только на чтение.',
      ],
      actions: ['retry-report', 'view-orders'],
    }
  }

  if (kind === 'reconciliation') {
    // Отказ по сходимости — отдельный экран (С4), сюда попадать не должен.
    return {
      title: 'Расчёт не сошёлся. Отчёт не выдан',
      body: ['Перечень непрошедших проверок показан на отдельном экране.'],
      actions: ['view-orders'],
    }
  }

  const lower = serverMessage.toLowerCase()
  if (kind === 'validation') {
    if (lower.includes('план') && lower.includes('счет')) return MISSING_ACCOUNT
    if (lower.includes('план') && lower.includes('счёт')) return MISSING_ACCOUNT
    if (lower.includes('нет ни одной')) return EMPTY_PERIOD
  }

  return COPY[kind]
}

/**
 * Вторая строка сообщения о периоде выбирается **по признаку в ответе сервера**,
 * а не клиентским разбором (UX-карта 3.4): дублировать правила разбора на клиенте
 * запрещено (ТЗ 5.3.3). Признака нет — показывается общая формулировка.
 */
function hintFromServer(serverMessage: string): string {
  const lower = serverMessage.toLowerCase()
  if (lower.includes('год')) return `Год указывается четырьмя цифрами. ${ACCEPTED_FORMATS}`
  if (lower.includes('месяц')) return `Месяц — число от 1 до 12 либо название месяца. ${ACCEPTED_FORMATS}`
  return `Проверьте месяц и год. ${ACCEPTED_FORMATS}`
}

