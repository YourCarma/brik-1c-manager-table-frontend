/**
 * Словарь целевых колонок — **единственное место**, где живут их названия и порядок.
 *
 * ТЗ 5.2: набор колонок в `by_column` будет расширяться (44 счёт, «БГ», способ
 * переноса брака ещё не утверждён). Таблицы обязаны строиться по фактическому
 * составу ключей ответа, а не по захардкоженному `CC/CD/CE`.
 * Критерий приёмки 11.9: появление новой колонки не ломает таблицы и не требует
 * правки кода таблиц — достаточно (по желанию) дописать строку сюда, чтобы у неё
 * появилось человекочитаемое название.
 *
 * Колонка, которой здесь нет, всё равно отобразится — под своим ключом из данных.
 */

export interface ColumnMeta {
  /** Ключ, как он приходит в `by_column`. */
  key: string
  /** Короткая подпись в шапке таблицы. Термин из глоссария ТЗ 3. */
  title: string
  /** Расшифровка — показывается подсказкой, чтобы шапка оставалась узкой. */
  hint: string
  /** Порядок слева направо. Незнакомые колонки уходят в конец. */
  order: number
}

