const BY_KEY = new Map(KNOWN.map((c) => [c.key.toLowerCase(), c]))

/** Метаданные колонки. Для незнакомого ключа — сам ключ в качестве названия. */
export function columnMeta(key: string): ColumnMeta {
  return (
    BY_KEY.get(key.toLowerCase()) ?? {
      key,
      title: key,
      hint: 'Колонка добавлена бэкендом. Описание пока не задано в словаре колонок',
      order: 1000,
    }
  )
}

/**
 * Состав колонок для таблицы — по фактическим ключам всех строк отчёта.
 * Порядок: сначала известные по словарю, затем новые (в порядке появления),
 * чтобы расширение контракта никогда не роняло вёрстку.
 */
export function resolveColumns(rows: Array<{ by_column: Record<string, unknown> }>): ColumnMeta[] {
  const seen = new Map<string, ColumnMeta>()
  let discovered = 0
  for (const row of rows) {
    for (const key of Object.keys(row.by_column ?? {})) {
      if (seen.has(key)) continue
      const meta = columnMeta(key)
      seen.set(key, meta.order === 1000 ? { ...meta, order: 1000 + discovered++ } : meta)
    }
  }
  return [...seen.values()].sort((a, b) => a.order - b.order || a.key.localeCompare(b.key, 'ru'))
}

