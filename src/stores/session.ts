/**
 * Сессия пользователя.
 *
 * ТЗ 10.3: авторизации на текущем этапе нет — доступ ограничен сетевым контуром
 * заказчика. Но точка входа спроектирована так, чтобы её можно было закрыть
 * экраном входа **без переработки навигации**: все рабочие маршруты — дети одного
 * корневого маршрута, глобальный `beforeEach` спрашивает именно этот стаб.
 *
 * Появление авторизации = замена содержимого этого файла и монтирование
 * компонента на `/login`. Ни один экран не переписывается.
 *
 * Интерфейс не хранит и не запрашивает реквизиты 1С: их здесь нет и не будет.
 */
import { defineStore } from 'pinia'
import { computed, ref } from 'vue'

export const useSessionStore = defineStore('session', () => {
  /** Пока авторизации нет — вход считается выполненным всегда. */
  const authenticated = ref(true)

  const isAuthenticated = computed(() => authenticated.value)

  return { isAuthenticated }
})
